const assert=require('node:assert/strict');
const fs=require('node:fs');
const Release=require('./reader-release.js');
const html=fs.readFileSync(__dirname+'/index.html','utf8');
assert.match(html,new RegExp('data-reader-build="'+Release.VERSION+'"'));
assert.match(html,new RegExp('体验版本 · '+Release.VERSION));
assert.equal(Release.VERSION,'index-25','the public preview address is pinned');
let assets=0;
for(const match of html.matchAll(/(?:src|href)="([^"#]+\.(?:js|css)(?:\?[^"#]*)?)"/g)){
  const url=new URL(match[1],'https://example.test/paper-bible-demo/');
  assert.equal(url.searchParams.get('v'),Release.VERSION,'mixed-release asset: '+match[1]);
  assert.match(url.searchParams.get('h'),/^[a-f0-9]{12}$/);assets++;
}
assert.ok(assets>=15,'check all local scripts and styles');
const before='https://example.test/paper-bible-demo/?v=type-1&paperRenderer=canvas&_refresh=old#reading';
const after=new URL(Release.refreshURL(before,12345));
assert.equal(after.origin,'https://example.test');
assert.equal(after.pathname,'/paper-bible-demo/');
assert.equal(after.searchParams.get('v'),Release.VERSION);
assert.equal(after.searchParams.has('_refresh'),false);
assert.equal(after.searchParams.get('paperRenderer'),'canvas');
assert.equal(after.hash,'#reading');
let click,reloads=0,replaced=null;
const loc={href:before,replace(url){replaced=url;},reload(){reloads++;}};
const link={addEventListener:(_,fn)=>{click=fn;}};
Release.init({getElementById:()=>link},loc);
assert.equal(replaced,null);assert.equal(reloads,0);
click({preventDefault(){}});assert.equal(replaced,after.href);
loc.href=after.href;click({preventDefault(){}});assert.equal(reloads,1);assert.equal(loc.href,after.href);
console.log('PASS fixed preview URL; '+assets+' fingerprinted resources; explicit reload preserves options, fragment and public URL');
