  const pages=new Map(),empty=Object.freeze([]);
  for(const [page,ordinal,bodyIndex,footerIndex,sourceRef,citation] of ledger){
    if(!pages.has(page))pages.set(page,[]);
    const marker=String.fromCharCode(0x245f+ordinal);
    pages.get(page).push(Object.freeze({page,ordinal,marker,sourceRef,citation,bodyIndex,footerIndex}));
  }
  for(const notes of pages.values())Object.freeze(notes);
  function notesForPage(page){return pages.get(Number(page))||empty;}
  function byOrdinal(page,ordinal){return notesForPage(page).find(n=>n.ordinal===Number(ordinal))||null;}

  const sources=new WeakMap();
  function index(source){
    if(!Array.isArray(source?.books))return null;
    if(sources.has(source))return sources.get(source);
    const names=new Map(),chapters=new Map(),verses=new Map();
    for(const book of source.books){
      for(const key of [book.name,book.short,book.code])if(key)names.set(key,book);
    }
    const idx={names,aliases:[...names.keys()].sort((a,b)=>b.length-a.length),chapters,verses};
    sources.set(source,idx);return idx;
  }
  function chapterOf(idx,book,n){
    if(!idx.chapters.has(book))idx.chapters.set(book,new Map((book.chapters||[]).map(c=>[c.chapter,c])));
    return idx.chapters.get(book).get(n);
  }
  function verseMap(idx,c){
    if(!idx.verses.has(c))idx.verses.set(c,new Map((c.verses||[]).map(row=>[row[0],row[1]])));
    return idx.verses.get(c);
  }
  // Only accept a complete unambiguous reference. "、" lists specific
  // verses (3:5、7 is NOT 3:5–7); ";" may carry a book to another chapter.
  // A range is inclusive. Never show a plausible fragment of a broken note.
  function resolveParts(citation,source){
    const idx=index(source);if(!idx||typeof citation!=='string'||citation.length>1024)return empty;
    const text=citation.normalize('NFKC').trim().replace(/[。. ]$/u,'');
    const tokens=text.split(/([、,;])/u),out=[];let book=null,chapter=0;
    for(let i=0;i<tokens.length;i+=2){
      let term=tokens[i].trim();
      const alias=idx.aliases.find(n=>term.startsWith(n));
      if(alias){book=idx.names.get(alias);chapter=0;term=term.slice(alias.length).trim();}
      const hit=/^(?:(\d+)\s*:\s*)?(\d+)(?:\s*[-—–]\s*(?:(\d+)\s*:\s*)?(\d+))?$/u.exec(term);
      if(!book||!hit||(!hit[1]&&(!chapter||tokens[i-1]===';')))return empty;
      const c1=hit[1]===undefined?chapter:Number(hit[1]),v1=Number(hit[2]);
      const c2=hit[3]===undefined?c1:Number(hit[3]),v2=hit[4]===undefined?v1:Number(hit[4]);
      if(![c1,v1,c2,v2].every(k=>Number.isSafeInteger(k)&&k>0)||c2<c1||(c1===c2&&v2<v1))return empty;
      if(!chapterOf(idx,book,c1)||!chapterOf(idx,book,c2))return empty;
      const part=[];
      for(let c=c1;c<=c2;c++){
        const ch=chapterOf(idx,book,c);if(!ch?.verses?.length)return empty;
        const verses=verseMap(idx,ch),first=c===c1?v1:ch.verses[0][0],last=c===c2?v2:ch.verses[ch.verses.length-1][0];
        if(!verses.has(first)||!verses.has(last)||last<first)return empty;
        for(let v=first;v<=last;v++){
          const value=verses.get(v);
          if(typeof value!=='string'||!value.trim())return empty;
          part.push({code:book.code,name:book.name,chapter:c,verse:v,text:value});
        }
      }
      out.push(part);
      chapter=c2;
    }
    return out;
  }
  function resolve(citation,source){return resolveParts(citation,source).flat();}
  function passages(note,source){return note?resolve(note.citation,source):empty;}
  return Object.freeze({seal,notesForPage,byOrdinal,passages,resolve,resolveParts});
