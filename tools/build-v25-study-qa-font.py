"""Add missing Chinese glyphs to the Q&A reader, not the paper font.

Requires fonttools and brotli. Build with a Google Fonts Noto Serif SC
variable TTF (ofl/notoserifsc/NotoSerifSC[wght].ttf), or pass --check
to verify the published subset after changing the Q&A library.
"""
import argparse
import hashlib
from io import BytesIO
import json
from pathlib import Path
import re
from unicodedata import category

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.unicodedata import script
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "fonts-study-qa.css"
VERSION = "Version 2.003-H1;hotconv 1.1.1;makeotfexe 2.6.0"
LICENSE = "paper-study-serif-OFL.txt"


def cmap(path):
    with TTFont(path) as font:
        return set(font.getBestCmap())


def declared_ranges(rule):
    ranges = re.search(r"unicode-range:([^;}]+)", rule)[1]
    for entry in ranges.split(","):
        start, _, end = entry.strip()[2:].partition("-")
        yield from range(int(start, 16), int(end or start, 16) + 1)


def available_base_glyphs():
    available = set()
    for sheet in ("fonts.css", "fonts-extra.css"):
        for rule in (ROOT / sheet).read_text(encoding="utf8").split("@font-face")[1:]:
            src = re.search(r'url\("([^"]+)"\)', rule)[1]
            available.update(cmap(ROOT / src).intersection(declared_ranges(rule)))
    return available


def needed_glyphs():
    items = json.loads((ROOT / "data/study-qa.json").read_text(encoding="utf8"))["items"]
    chars = {char for item in items for char in item["q"] + item["a"]} | {"•"}
    # Cover Han, ASCII and shared punctuation/symbols; leave foreign-script
    # runs, phonetic marks and combining sequences to their existing fonts.
    chinese_and_common = {
        ord(c) for c in chars if not c.isspace() and (
            c.isascii() or script(c) == "Hani"
            or (script(c) == "Zyyy" and category(c)[0] in "NPS")
        )
    }
    return chinese_and_common - available_base_glyphs()


def verify(codes):
    css = CSS.read_text(encoding="utf8")
    asset = ROOT / re.search(r'url\("(fonts/paper-study-serif-[a-f0-9]+\.woff2)"\)', css)[1]
    assert asset.stem.endswith(hashlib.sha256(asset.read_bytes()).hexdigest()[:12]), asset
    assert set(declared_ranges(css)) == cmap(asset) == codes, "Rebuild the Q&A font from the current corpus"
    print(f"{asset.name}: {len(codes)} supplemental glyphs ({sum(script(chr(c)) == 'Hani' for c in codes)} Han), {asset.stat().st_size} bytes")


def build(source, codes):
    with TTFont(source, recalcTimestamp=False) as font:
        names = font["name"]
        copyright_notice = names.getDebugName(0)
        assert names.getDebugName(1).startswith("Noto Serif SC")
        assert names.getDebugName(5) == VERSION
        assert "SIL Open Font License" in names.getDebugName(13)
        missing = codes - set(font.getBestCmap())
        assert not missing, [f"U+{code:X}" for code in sorted(missing)]
        options = subset.Options()
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=codes)
        sub.subset(font)
        instantiateVariableFont(font, {"wght": 400}, inplace=True)
        assert font["OS/2"].usWeightClass == 400
        rename = {1: "Paper Study Serif", 2: "Regular", 3: "PaperStudySerif-Regular-V25",
                  4: "Paper Study Serif Regular", 6: "PaperStudySerif-Regular",
                  16: "Paper Study Serif", 17: "Regular", 25: "PaperStudySerif"}
        for record in list(font["name"].names):
            if record.nameID in rename:
                font["name"].setName(rename[record.nameID], record.nameID, record.platformID,
                                     record.platEncID, record.langID)
        font.flavor = "woff2"
        output = BytesIO()
        font.save(output)
        data = output.getvalue()
    asset = f"paper-study-serif-{hashlib.sha256(data).hexdigest()[:12]}.woff2"
    (ROOT / "fonts" / asset).write_bytes(data)
    ofl = (ROOT / "fonts" / "LICENSE.txt").read_text(encoding="utf8")
    (ROOT / "fonts" / LICENSE).write_bytes(
        f"{copyright_notice}\nNoto is a trademark of Google Inc.\n"
        f"Paper Study Serif is a renamed regular-weight subset of Noto Serif SC.\n\n{ofl}".encode("utf8")
    )
    ranges = ",".join(f"U+{code:X}" for code in sorted(codes))
    CSS.write_bytes((
        f"/* Generated by tools/build-v25-study-qa-font.py. Q&A only; fonts/{LICENSE}.\n"
        f"   Noto Serif SC {VERSION}; source SHA-256 {hashlib.sha256(source.read_bytes()).hexdigest()}. */\n"
        f'@font-face{{font-family:PaperStudySerif;src:url("fonts/{asset}") format("woff2");'
        f"font-weight:400;font-style:normal;font-display:swap;unicode-range:{ranges};}}\n"
    ).encode("utf8"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("source", nargs="?", type=Path)
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    codes = needed_glyphs()
    if not args.check:
        build(args.source, codes)
    verify(codes)


if __name__ == "__main__":
    main()
